/**
 * Fallback translator using a local dictionary lookup with simple keyword rules
 * to provide a high quality mock translation of typical classroom texts.
 */
export function getLocalFallbackTranslation(text: string, lang: 'en' | 'fr'): string {
  const trimmed = text.trim();
  
  // Exact match lookup
  if (LOCAL_TRANSLATIONS[trimmed]) {
    return LOCAL_TRANSLATIONS[trimmed][lang];
  }

  // Look for partial sentence matches in existing translations
  for (const [key, value] of Object.entries(LOCAL_TRANSLATIONS)) {
    if (trimmed.toLowerCase().includes(key.toLowerCase())) {
      return value[lang];
    }
  }

  // Common vocabulary replacements
  let translated = trimmed;
  const vocab: Record<string, { en: string; fr: string }> = {
    "SENA": { en: "SENA", fr: "SENA" },
    "aprendiz": { en: "apprentice", fr: "apprenti" },
    "aprendices": { en: "apprentices", fr: "apprentis" },
    "instructor": { en: "instructor", fr: "instructeur" },
    "instructores": { en: "instructors", fr: "instructeurs" },
    "formación": { en: "training", fr: "formation" },
    "competencia": { en: "competence", fr: "compétence" },
    "reglamento": { en: "regulations", fr: "règlement" },
    "bienestar": { en: "welfare", fr: "bien-être" },
    "inducción": { en: "induction", fr: "intégration" },
    "entorno": { en: "environment", fr: "environnement" },
    "aula": { en: "classroom", fr: "salle de classe" },
    "proyecto": { en: "project", fr: "projet" },
    "evidencia": { en: "evidence", fr: "preuve" },
    "evidencias": { en: "evidences", fr: "preuves" },
    "unidad": { en: "unit", fr: "unité" },
    "colegio": { en: "college", fr: "collège" },
    "programa": { en: "program", fr: "programme" },
    "proceso": { en: "process", fr: "processus" },
    "derecho": { en: "right", fr: "droit" },
    "derechos": { en: "rights", fr: "droits" },
    "deber": { en: "duty", fr: "devoir" },
    "deberes": { en: "duties", fr: "devoirs" }
  };

  // Basic word replacement for fallback context
  for (const [key, words] of Object.entries(vocab)) {
    const regex = new RegExp(`\\b${key}\\b`, 'gi');
    translated = translated.replace(regex, words[lang]);
  }

  // If translation did not change substantially and no key matched, append language flag
  if (translated === trimmed) {
    return lang === 'en' ? `[EN Translation]: ${trimmed}` : `[FR Traduction]: ${trimmed}`;
  }

  return translated;
}
